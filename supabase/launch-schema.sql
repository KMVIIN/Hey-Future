drop policy if exists "profile self read" on public.profiles;
create policy "profile self read" on public.profiles for select using (auth.uid() = id);
drop policy if exists "profile self update" on public.profiles;
create policy "profile self update" on public.profiles for update using (auth.uid() = id);

drop policy if exists "subscription self read" on public.subscriptions;
create policy "subscription self read" on public.subscriptions for select using (auth.uid() = user_id);

drop policy if exists "usage self read" on public.usage_events;
create policy "usage self read" on public.usage_events for select using (auth.uid() = user_id);

drop policy if exists "state self read" on public.user_state;
create policy "state self read" on public.user_state for select using (auth.uid() = user_id);
drop policy if exists "state self insert" on public.user_state;
create policy "state self insert" on public.user_state for insert with check (auth.uid() = user_id);
drop policy if exists "state self update" on public.user_state;
create policy "state self update" on public.user_state for update using (auth.uid() = user_id);

